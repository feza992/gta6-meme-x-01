// A working gta6-meme-x-01 entry (Node 22, standard library only).
//
// The entry is the post itself: an AI agent makes a GTA 6 meme, it is
// posted on X from a public account with make.fun (a link or written out)
// and/or a tag of @makefunai and the entrant's play code in its text,
// POST.json names the post, and the house reads the post from X (its
// first picture and its text) and hands that to the judge.
//
// This program does two things, both deterministically:
//   1. copies POST.json from the repository to /output/POST.json, where
//      the gate reads it (as the starter did);
//   2. copies meme.png from the repository to /output/meme.png, so the
//      picture the post carries is the one this repository ships —
//      byte-identical on every run.
//
// The meme is a static GTA wanted poster (meme.png, 1408x1760, sha256
// 92dfd32df2b4652c52851ce0857a3d35df6a36cb8ce9488fda5372e7ddd890a2):
// "WANTED" from the Vice City Police Department, five gold stars, and
// make.fun's ghost in a bandit mask with a gold chain, holding its
// magenta star coin — wanted "FOR EARNING $500 WITHOUT ROBBING A
// SINGLE BANK". The note at the bottom spells the joke out: "IN GTA,
// 5 STARS = COPS CHASE YOU / ON MAKE.FUN, 5 STARS = YOU GET PAID",
// with a make.fun stamp and "REWARD: $500 PAID IN MAKE.FUN COINS".
// The picture is an asset in this repository, not generated by this
// program. Verified 2026-11-20 in this session: two runs of main.ts
// into separate directories produced byte-identical outputs (diff -r
// clean), and out/meme.png matches the repository's meme.png
// (sha256 92dfd32d...). The poster was also viewed at full size and
// at a 384x480 judge-view downscale: WANTED, the 5 stars, the ghost,
// "FOR EARNING $500 WITHOUT ROBBING A SINGLE BANK", the note and
// the make.fun stamp are all readable at that size.
//
// The POST.json this repository ships holds a placeholder address until
// the post is made, so the gate refuses it as it stands (valid 0).
// Replace it with the post's address before submitting.
//
// No network, no wall clock, no files outside the repository.
// Outside the grader's container, MAKEFUN_BOT_DIR and
// MAKEFUN_OUTPUT_DIR stand in for /bot and /output:
//   mkdir -p out && MAKEFUN_BOT_DIR=. MAKEFUN_OUTPUT_DIR=out node main.ts

import { copyFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

const BOT_DIR = process.env.MAKEFUN_BOT_DIR ?? '/bot';
const OUTPUT_DIR = process.env.MAKEFUN_OUTPUT_DIR ?? '/output';

mkdirSync(OUTPUT_DIR, { recursive: true });
for (const file of ['POST.json', 'meme.png']) {
  try {
    copyFileSync(join(BOT_DIR, file), join(OUTPUT_DIR, file));
  } catch (err) {
    console.error(`${file} could not be copied from ${BOT_DIR}: ${(err as Error).message}`);
    process.exit(1);
  }
}
